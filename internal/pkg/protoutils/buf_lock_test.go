func TestDefaultBufCacheDir(t *testing.T) {
	t.Run("BUF_CACHE_DIR_wins_over_everything", func(t *testing.T) {
		t.Setenv("BUF_CACHE_DIR", "/custom/buf-cache")
		t.Setenv("XDG_CACHE_HOME", "/ignored/xdg")
		t.Setenv("HOME", "/ignored/home")
		assert.Equal(t, "/custom/buf-cache", defaultBufCacheDir())
	})

	t.Run("BUF_CACHE_DIR_used_verbatim_without_buf_suffix", func(t *testing.T) {
		t.Setenv("BUF_CACHE_DIR", "/already/has/buf")
		got := defaultBufCacheDir()
		assert.Equal(t, "/already/has/buf", got, "buf CLI does NOT append /buf when BUF_CACHE_DIR is set")
	})

	t.Run("BUF_CACHE_DIR_leading_and_trailing_whitespace_stripped", func(t *testing.T) {
		t.Setenv("BUF_CACHE_DIR", "   /trimmed/path   ")
		assert.Equal(t, "/trimmed/path", defaultBufCacheDir())
	})

	t.Run("BUF_CACHE_DIR_empty_falls_through", func(t *testing.T) {
		t.Setenv("BUF_CACHE_DIR", "")
		t.Setenv("XDG_CACHE_HOME", "/x")
		if runtime.GOOS == "windows" {
			t.Setenv("LocalAppData", `C:\AppData`)
			assert.Equal(t, filepath.Join(`C:\AppData`, "buf"), defaultBufCacheDir())
			return
		}
		assert.Equal(t, "/x/buf", defaultBufCacheDir())
	})

	t.Run("BUF_CACHE_DIR_whitespace_only_falls_through", func(t *testing.T) {
		if runtime.GOOS == "windows" {
			t.Skip("unix-only fallthrough test")
		}
		t.Setenv("BUF_CACHE_DIR", "   \t  ")
		t.Setenv("XDG_CACHE_HOME", "/xdg")
		assert.Equal(t, "/xdg/buf", defaultBufCacheDir())
	})

	t.Run("unix_XDG_CACHE_HOME_appends_buf", func(t *testing.T) {
		if runtime.GOOS == "windows" {
			t.Skip("unix-only test")
		}
		t.Setenv("BUF_CACHE_DIR", "")
		t.Setenv("XDG_CACHE_HOME", "/xdg/home")
		assert.Equal(t, "/xdg/home/buf", defaultBufCacheDir())
	})

	t.Run("unix_falls_back_to_home_dot_cache", func(t *testing.T) {
		if runtime.GOOS == "windows" {
			t.Skip("unix-only test")
		}
		t.Setenv("BUF_CACHE_DIR", "")
		t.Setenv("XDG_CACHE_HOME", "")
		t.Setenv("HOME", "/home/tester")
		assert.Equal(t, "/home/tester/.cache/buf", defaultBufCacheDir())
	})

	t.Run("macos_does_NOT_use_library_caches", func(t *testing.T) {
		if runtime.GOOS != "darwin" {
			t.Skip("darwin-only test — buf uses XDG on macOS, not ~/Library/Caches")
		}
		t.Setenv("BUF_CACHE_DIR", "")
		t.Setenv("XDG_CACHE_HOME", "")
		t.Setenv("HOME", "/Users/tester")
		got := defaultBufCacheDir()
		assert.Equal(t, "/Users/tester/.cache/buf", got)
		assert.NotContains(t, got, "Library/Caches",
			"buf deliberately avoids ~/Library/Caches on macOS — see app_unix.go comment")
	})

	t.Run("windows_uses_LocalAppData", func(t *testing.T) {
		if runtime.GOOS != "windows" {
			t.Skip("windows-only test")
		}
		t.Setenv("BUF_CACHE_DIR", "")
		t.Setenv("LocalAppData", `C:\Users\x\AppData\Local`)
		assert.Equal(t, `C:\Users\x\AppData\Local\buf`, defaultBufCacheDir())
	})
}

