func TestSplitKV(t *testing.T) {
	t.Parallel()

	cases := []struct {
		in     string
		wantK  string
		wantV  string
		wantOk bool
	}{
		{"name: foo", "name", "foo", true},
		{"name:foo", "name", "foo", true},
		{"name:   foo   ", "name", "foo", true},
		{"name: \"quoted value\"", "name", "quoted value", true},
		{"name: 'single'", "name", "single", true},
		{"name: v # comment here", "name", "v", true},
		{"nocolon", "", "", false},
		{":leading colon", "", "", false},
		{"", "", "", false},
	}
	for _, tc := range cases {
		t.Run(tc.in, func(t *testing.T) {
			k, v, ok := splitKV(tc.in)
			assert.Equal(t, tc.wantOk, ok)
			if ok {
				assert.Equal(t, tc.wantK, k)
				assert.Equal(t, tc.wantV, v)
			}
		})
	}
}
