func TestResolveBufDepsWith(t *testing.T) {
	t.Parallel()

	t.Run("happy_path_single_dep", func(t *testing.T) {
		c := newCache(t)
		c.addProtovalidate("b5", fixtureCommitProtovalidate)
		src := t.TempDir()
		writeBufLock(t, src, bufLockV2Single(fixtureCommitProtovalidate, fixtureDigestB5))

		got := resolveBufDepsWith(src, c.root)
		require.Len(t, got, 1)
		assert.True(t, strings.HasSuffix(got[0], "files"))
	})

	t.Run("multiple_deps_all_resolve", func(t *testing.T) {
		c := newCache(t)
		c.addProtovalidate("b5", fixtureCommitProtovalidate)
		c.addGoogleapisMinimal("b5", fixtureCommitGoogleapis)
		src := t.TempDir()
		writeBufLock(t, src, bufLockV2MultipleDeps())

		got := resolveBufDepsWith(src, c.root)
		require.Len(t, got, 2)
	})

	t.Run("some_deps_missing_from_cache_returns_only_resolved", func(t *testing.T) {
		c := newCache(t)
		c.addProtovalidate("b5", fixtureCommitProtovalidate)
		src := t.TempDir()
		writeBufLock(t, src, bufLockV2MultipleDeps())

		got := resolveBufDepsWith(src, c.root)
		require.Len(t, got, 1)
		assert.Contains(t, got[0], "protovalidate")
	})

	t.Run("no_source_root_returns_nil", func(t *testing.T) {
		assert.Nil(t, resolveBufDepsWith("", t.TempDir()))
	})

	t.Run("no_cache_root_returns_nil", func(t *testing.T) {
		src := t.TempDir()
		writeBufLock(t, src, bufLockV2Single(fixtureCommitProtovalidate, fixtureDigestB5))
		assert.Nil(t, resolveBufDepsWith(src, ""))
	})

	t.Run("missing_buf_lock_returns_nil", func(t *testing.T) {
		c := newCache(t)
		c.addProtovalidate("b5", fixtureCommitProtovalidate)
		assert.Nil(t, resolveBufDepsWith(t.TempDir(), c.root))
	})

	t.Run("empty_buf_lock_returns_nil", func(t *testing.T) {
		c := newCache(t)
		src := t.TempDir()
		writeBufLock(t, src, "version: v2\n")
		assert.Nil(t, resolveBufDepsWith(src, c.root))
	})

	t.Run("malformed_buf_lock_returns_nil", func(t *testing.T) {
		c := newCache(t)
		src := t.TempDir()
		writeBufLock(t, src, "not yaml at all\n🦑\n- - - -")
		got := resolveBufDepsWith(src, c.root)
		assert.Empty(t, got)
	})

	t.Run("all_deps_missing_returns_empty", func(t *testing.T) {
		c := newCache(t)
		src := t.TempDir()
		writeBufLock(t, src, bufLockV2Single(fixtureCommitProtovalidate, fixtureDigestB5))
		got := resolveBufDepsWith(src, c.root)
		assert.Empty(t, got)
	})

	t.Run("deduplicates_paths", func(t *testing.T) {
		c := newCache(t)
		c.addProtovalidate("b5", fixtureCommitProtovalidate)
		src := t.TempDir()
		body := bufLockV2Single(fixtureCommitProtovalidate, fixtureDigestB5) +
			"  - name: buf.build/bufbuild/protovalidate\n" +
			"    commit: " + fixtureCommitProtovalidate + "\n" +
			"    digest: " + fixtureDigestB5 + "\n"
		writeBufLock(t, src, body)

		got := resolveBufDepsWith(src, c.root)
		assert.Len(t, got, 1)
	})

	t.Run("b4_and_b5_both_cached_picks_per_digest", func(t *testing.T) {
		c := newCache(t)
		c.addProtovalidate("b4", fixtureCommitProtovalidate)
		c.addProtovalidate("b5", fixtureCommitProtovalidate)

		src := t.TempDir()
		writeBufLock(t, src, bufLockV2Single(fixtureCommitProtovalidate, fixtureDigestB4))
		got := resolveBufDepsWith(src, c.root)
		require.Len(t, got, 1)
		assert.Contains(t, got[0], filepath.Join("v3", "modules", "b4"))

		src2 := t.TempDir()
		writeBufLock(t, src2, bufLockV2Single(fixtureCommitProtovalidate, fixtureDigestB5))
		got2 := resolveBufDepsWith(src2, c.root)
		require.Len(t, got2, 1)
		assert.Contains(t, got2[0], filepath.Join("v3", "modules", "b5"))
	})

	t.Run("v1_lock_format_works", func(t *testing.T) {
		c := newCache(t)
		c.addProtovalidate("b5", fixtureCommitProtovalidate)
		src := t.TempDir()
		body := `version: v1
deps:
  - remote: buf.build
    owner: bufbuild
    repository: protovalidate
    commit: ` + fixtureCommitProtovalidate + `
    digest: ` + fixtureDigestB5 + `
`
		writeBufLock(t, src, body)
		got := resolveBufDepsWith(src, c.root)
		require.Len(t, got, 1)
	})
}

func TestResolveBufDepsFromLock(t *testing.T) {
	t.Parallel()

	t.Run("valid_lock_cached_module_returns_files_dir", func(t *testing.T) {
		c := newCache(t)
		c.addProtovalidate("b5", fixtureCommitProtovalidate)

		lock := []byte(bufLockV2Single(fixtureCommitProtovalidate, fixtureDigestB5))
		got := resolveBufDepsFromLockWith(lock, c.root)
		require.Len(t, got, 1)
		assert.True(t, strings.HasSuffix(got[0], "files"))
	})

	t.Run("nil_lock_returns_nil", func(t *testing.T) {
		c := newCache(t)
		assert.Nil(t, resolveBufDepsFromLockWith(nil, c.root))
	})

	t.Run("garbage_lock_returns_nil", func(t *testing.T) {
		c := newCache(t)
		assert.Nil(t, resolveBufDepsFromLockWith([]byte("garbage"), c.root))
	})

	t.Run("empty_cache_root_returns_nil", func(t *testing.T) {
		lock := []byte(bufLockV2Single(fixtureCommitProtovalidate, fixtureDigestB5))
		assert.Nil(t, resolveBufDepsFromLockWith(lock, ""))
	})

	t.Run("multiple_deps_all_cached", func(t *testing.T) {
		c := newCache(t)
		c.addProtovalidate("b5", fixtureCommitProtovalidate)
		c.addGoogleapisMinimal("b5", fixtureCommitGoogleapis)

		lock := []byte(bufLockV2MultipleDeps())
		got := resolveBufDepsFromLockWith(lock, c.root)
		require.Len(t, got, 2)
	})

	t.Run("deduplicates_identical_paths", func(t *testing.T) {
		c := newCache(t)
		c.addProtovalidate("b5", fixtureCommitProtovalidate)

		body := bufLockV2Single(fixtureCommitProtovalidate, fixtureDigestB5) +
			"  - name: buf.build/bufbuild/protovalidate\n" +
			"    commit: " + fixtureCommitProtovalidate + "\n" +
			"    digest: " + fixtureDigestB5 + "\n"
		got := resolveBufDepsFromLockWith([]byte(body), c.root)
		assert.Len(t, got, 1)
	})

	t.Run("missing_dep_in_cache_skipped", func(t *testing.T) {
		c := newCache(t)
		// only protovalidate cached, not googleapis
		c.addProtovalidate("b5", fixtureCommitProtovalidate)

		lock := []byte(bufLockV2MultipleDeps())
		got := resolveBufDepsFromLockWith(lock, c.root)
		require.Len(t, got, 1)
		assert.Contains(t, got[0], "protovalidate")
	})
}

